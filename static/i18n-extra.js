const _xtRegex={};
function _xtPatterns(code){
  if(_xtRegex[code])return _xtRegex[code];
  const out=[];
  for(const [en,tr] of Object.entries(XT[code].phrases)){
    if(!en.includes('{}'))continue;
    const re=new RegExp('^'+en.split('{}').map(p=>p.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')).join('(.+?)')+'$');
    out.push([re,tr]);
  }
  return _xtRegex[code]=out;
}
// Translate an English kiosk sentence for Kannada/Tamil/Bengali. Unknown text stays English instead of being guessed.
function TR(code,en){
  if(!EXTRA_UI.includes(code)||typeof en!=='string')return en;
  const t=XT[code].phrases[en];if(t)return t;
  for(const [re,tr] of _xtPatterns(code)){const m=en.match(re);if(m){let i=1;return tr.replace(/\{\}/g,()=>m[i++])}}
  return en;
}
function pick(obj,code){
  if(obj[code]!==undefined)return obj[code];
  return EXTRA_UI.includes(code)&&typeof obj.en==='string'?TR(code,obj.en):obj.en;
}
